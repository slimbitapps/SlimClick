const ALL: Record<string, S> = { de, en, fr, es, it };

export const lang = (() => {
  const l = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return ALL[l] ? l : 'en';
})();
const dict = ALL[lang];

export function tr(key: keyof S, params?: Record<string, string | number>) {
  let s = dict[key] ?? en[key];
  if (params) for (const k in params) s = s.split(`{${k}}`).join(String(params[k]));
  return s;
}
